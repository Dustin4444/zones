//! Hand-pinned literal ABI bytes generated independently with Foundry `cast`.
//!
//! Reproduction commands and protocol provenance live in
//! `crates/checker/MODEL_VECTORS.md`. Model code never calls a production queue,
//! fee, payload, Inbox, Outbox, or transition helper to obtain these values.

pub(super) fn literal_bytes(value: &str) -> Vec<u8> {
    alloy_primitives::hex::decode(value).expect("checked-in vector must be valid hex")
}

